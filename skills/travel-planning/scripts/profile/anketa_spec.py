QUESTIONS_BY_ID: dict[str, Question] = {}
SECTION_BY_QID: dict[str, Section] = {}
for _sec in ANKETA_SECTIONS:
    for _q in _sec.questions():
        QUESTIONS_BY_ID[_q.id] = _q
        SECTION_BY_QID[_q.id] = _sec


def get_question(qid: str) -> Optional[Question]:
    return QUESTIONS_BY_ID.get(qid)


def get_section(section_id: str) -> Optional[Section]:
    for s in ANKETA_SECTIONS:
        if s.id == section_id:
            return s
    return None


