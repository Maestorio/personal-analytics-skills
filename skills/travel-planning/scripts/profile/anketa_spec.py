"""Спека вопросов анкеты — single source of truth.

ANKETA_SECTIONS — список Section, каждый содержит:
  - id         : kebab/snake-case slug для внутренних ссылок
  - title      : заголовок секции в DOCX
  - marker     : "[ОБЯЗАТЕЛЬНО]" | "[ВАЖНО]" | "[ОПЦИОНАЛЬНО]" | ""
  - profile_h2 : H2 секции в profile.md (например "## Состав группы")
  - items      : список Question или Subheader (для секций с подвопросами 4.1/4.2/…)

Question:
  - id         : qid вида "{section_id}.{slot}"
  - type       : "text" | "single" | "multi"
  - text       : сам вопрос (bold)
  - hint       : пример (italic grey, опц.)
  - options    : list[(value, description)] для choice-типов

Subheader:
  - title      : "4.1 Подход к планированию"

Архетип `группа_архетип` живёт в YAML frontmatter, не в теле — для него
специальный qid `archetype` с type="single", options из ARCHETYPE_VALUES.

Используется build_docx (рендер) и parse_docx / assemble_profile_md
(обратный путь).
"""
from __future__ import annotations
from dataclasses import dataclass, field
from typing import Optional


# --- Допустимые архетипы (см. profile-management.md §7.5) -------------------
# Legacy-имена (ARCHETYPE_LEGACY_ALIASES) принимаются на входе и
# нормализуются в канонические: `родители_60_плюс` → `взрослые_50_плюс`,
# `независимые_соло_пара` → `самостоятельные`. Новые анкеты пишут канонические.
ARCHETYPE_VALUES = [
    "самостоятельные",
    "семья_с_детьми",
    "взрослые_50_плюс",
    "люкс",
]
ARCHETYPE_LEGACY_ALIASES = {
    "родители_60_плюс": "взрослые_50_плюс",
    "независимые_соло_пара": "самостоятельные",
}


@dataclass
class Question:
    id: str
    type: str  # "text" | "single" | "multi"
    text: str
    hint: str = ""
    options: list = field(default_factory=list)  # list[(value, desc)]


@dataclass
class Subheader:
    title: str


@dataclass
class Section:
    id: str
    title: str
    marker: str
    profile_h2: str
    items: list = field(default_factory=list)  # Question | Subheader

    def questions(self):
        """Все Question, без Subheader."""
        return [it for it in self.items if isinstance(it, Question)]


